#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

export function calculateVersionCode(version) {
  const parts = version.split('-')[0].split('.').map(Number);
  const major = parts[0] || 0;
  const minor = parts[1] || 0;
  const patch = parts[2] || 0;
  // Formula: major * 1000000 + minor * 1000 + patch (e.g. 1.2.0 -> 1002000)
  return major * 1000000 + minor * 1000 + patch;
}

const isDirectRun = Boolean(process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]));

export function updateVersionTargets(targetVersion, workspaceRoot = rootDir) {
  const rootDir = workspaceRoot;

  function updateJsonVersion(filePath, label) {
    if (fs.existsSync(filePath)) {
      const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
      const oldVersion = data.version;
      data.version = targetVersion;
      fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n');
      console.log(`✓ Updated ${label}: ${oldVersion} -> ${targetVersion}`);
    }
  }

  // 1. Root package.json
  updateJsonVersion(path.join(rootDir, 'package.json'), 'root package.json');

  // 2. apps/extension/package.json and manifest.json
  updateJsonVersion(path.join(rootDir, 'apps/extension/package.json'), 'apps/extension/package.json');
  updateJsonVersion(path.join(rootDir, 'apps/extension/public/manifest.json'), 'extension manifest.json');

  // 3. packages/common/package.json
  updateJsonVersion(path.join(rootDir, 'packages/common/package.json'), 'packages/common/package.json');

  // 4. apps/native/package.json
  updateJsonVersion(path.join(rootDir, 'apps/native/package.json'), 'apps/native/package.json');

  // 5. apps/hub/package.json
  updateJsonVersion(path.join(rootDir, 'apps/hub/package.json'), 'apps/hub/package.json');

  // 6. apps/native/src-tauri/tauri.conf.json
  updateJsonVersion(path.join(rootDir, 'apps/native/src-tauri/tauri.conf.json'), 'apps/native/src-tauri/tauri.conf.json');

  // 7. apps/native/src-tauri/Cargo.toml
  const cargoTomlPath = path.join(rootDir, 'apps/native/src-tauri/Cargo.toml');
  if (fs.existsSync(cargoTomlPath)) {
    let cargoToml = fs.readFileSync(cargoTomlPath, 'utf8');
    cargoToml = cargoToml.replace(/^version = "[^"]+"/m, `version = "${targetVersion}"`);
    fs.writeFileSync(cargoTomlPath, cargoToml);
    console.log(`✓ Updated apps/native/src-tauri/Cargo.toml -> ${targetVersion}`);
  }

  // 8. apps/native/src-tauri/gen/android/app/tauri.properties (if Android initialized)
  const androidPropsPath = path.join(rootDir, 'apps/native/src-tauri/gen/android/app/tauri.properties');
  if (fs.existsSync(androidPropsPath)) {
    const newCode = calculateVersionCode(targetVersion);
    const propsContent = `// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\ntauri.android.versionName=${targetVersion}\ntauri.android.versionCode=${newCode}\n`;
    fs.writeFileSync(androidPropsPath, propsContent);
    console.log(`✓ Updated Android tauri.properties: ${targetVersion} (code: ${newCode})`);
  }

  // 9. README.md version badge
  const readmePath = path.join(rootDir, 'README.md');
  if (fs.existsSync(readmePath)) {
    let readme = fs.readFileSync(readmePath, 'utf8');
    readme = readme.replace(/https:\/\/img\.shields\.io\/badge\/Version-[^\s)]+-blue\.svg/g, `https://img.shields.io/badge/Version-${targetVersion}-blue.svg`);
    fs.writeFileSync(readmePath, readme);
    console.log(`✓ Updated README.md version badge -> ${targetVersion}`);
  }

  // 10. packages/common/src/lib/postman.ts export metadata
  const postmanLibPath = path.join(rootDir, 'packages/common/src/lib/postman.ts');
  if (fs.existsSync(postmanLibPath)) {
    let postmanLib = fs.readFileSync(postmanLibPath, 'utf8');
    postmanLib = postmanLib.replace(/_postman_exported_using:\s*'AirREST\/[^']+'/g, `_postman_exported_using: 'AirREST/${targetVersion}'`);
    fs.writeFileSync(postmanLibPath, postmanLib);
    console.log(`✓ Updated packages/common/src/lib/postman.ts export metadata -> ${targetVersion}`);
  }

}

if (isDirectRun) {
  const targetVersion = process.argv[2]?.trim().replace(/^v/, '');

  if (!targetVersion || !/^\d+\.\d+\.\d+(-[a-zA-Z0-9.]+)?$/.test(targetVersion)) {
    console.error('Usage: npm run version -- <version>');
    console.error('Example: npm run version -- 1.2.0');
    process.exit(1);
  }

  updateVersionTargets(targetVersion);
  console.log(`\nAll packages successfully bumped to v${targetVersion}!`);
  console.log('Ready to commit and tag:');
  console.log('  git add .');
  console.log(`  git commit -m "chore(release): bump unified version to v${targetVersion}"`);
  console.log(`  git tag v${targetVersion}`);
  console.log('  git push origin <branch> --tags');
}
